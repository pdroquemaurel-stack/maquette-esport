/* Rang affiché : « 1ᵉʳ », « 12ᵉ » ; « 1st », « 12th » ; « 12 » en arabe (la phrase porte « المركز ») */
function rangFr(n) { return n === 1 ? "1ᵉʳ" : n + "ᵉ"; }
function rangEn(n) {
  const fin = n % 100 >= 11 && n % 100 <= 13 ? "th" : ({ 1: "st", 2: "nd", 3: "rd" })[n % 10] || "th";
  return n + fin;
}

